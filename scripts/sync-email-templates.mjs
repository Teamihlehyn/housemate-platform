#!/usr/bin/env node
// Copies the designer's email templates (docs/design/emails/<name>.html + <name>.txt) into
// lib/emails/templates.ts, so they're bundled at build time (no runtime file reads).
// The subject is the HTML <title>. Usage: node scripts/sync-email-templates.mjs
import { readFileSync, writeFileSync, existsSync } from "fs";
import { pathToFileURL } from "url";

// Designer notes in HTML comments must not reach inboxes. Outlook conditional comments
// (<!--[if mso]>…, <!--[if !mso]><!-->, <!--<![endif]-->) are kept: they're rendering logic.
export function stripComments(html) {
  return html.replace(/<!--(?!\[if)(?!<!\[endif\])(?!>)[\s\S]*?-->/g, "");
}

export const TEMPLATES = {
  survey: ["first_name", "survey_url", "unsubscribe_url"],
  invite: ["invite_url", "code"],
};
function main() {
  let out = `// GENERATED by scripts/sync-email-templates.mjs from docs/design/emails/.
  // Don't edit by hand: change the design files and re-run the script.
  `;
  for (const [name, need] of Object.entries(TEMPLATES)) {
    const html = `docs/design/emails/${name}.html`;
    const txt = `docs/design/emails/${name}.txt`;
    if (!existsSync(html) || !existsSync(txt)) {
      console.error(`Missing ${html} or ${txt}.`);
      process.exit(1);
    }
    const original = readFileSync(html, "utf8");
    const h = stripComments(original);
    const t = readFileSync(txt, "utf8");
    const subject = (/<title>([^<]*)<\/title>/i.exec(h)?.[1] || "").trim();
    if (!subject) console.warn(`warning: ${html} has no <title> (used as the subject)`);
    for (const [kind, body] of [["html", h], ["txt", t]]) {
      for (const p of need) if (!body.includes(`{{${p}}}`)) console.warn(`warning: ${name}.${kind} has no {{${p}}}`);
      const literal = body.match(/\[[A-Z][A-Z ]+\]/g);
      if (literal) console.warn(`warning: ${name}.${kind} still contains ${[...new Set(literal)].join(" ")}`);
    }
    const N = name.toUpperCase();
    out += `
  export const ${N}_SUBJECT = ${JSON.stringify(subject.replace(/&amp;/g, "&"))};
  export const ${N}_HTML = ${JSON.stringify(h)};
  export const ${N}_TEXT = ${JSON.stringify(t)};
  `;
  }
  writeFileSync("lib/emails/templates.ts", out);
  console.log("Wrote lib/emails/templates.ts");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
